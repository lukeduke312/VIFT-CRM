-- Datum:  2026-11-20
-- Status: EJ INSTALLERAD. Kräver separat, uttryckligt GO innan körning
--         i STAGING eller LIVE.
--
-- BAKGRUND: Supabase Performance Advisor har flaggat push_subscriptions
-- för ett saknat index. Denna migration föreslås INTE enbart på grund av
-- den varningen — den är verifierad mot de FAKTISKA, verkliga frågorna i
-- supabase/functions/send-push/index.ts och service-monitor/index.ts
-- (lästa i sin helhet denna session, inte antagna):
--
--   send-push/index.ts rad 247-249:
--     .eq('endpoint', testEndpoint).eq('user_id', caller.id).is('revoked_at', null)
--   send-push/index.ts rad 387-390:
--     .is('revoked_at', null)                           (ingen user_id-filter — broadcast)
--   send-push/index.ts rad 506-519:
--     .is('revoked_at', null)  [+ villkorligt] .eq('user_id', targetUserId)
--   service-monitor/index.ts rad 184-187:
--     .is('revoked_at', null)                           (ingen user_id-filter — hela tabellen,
--                                                          grupperas sedan klient-sidigt per user_id)
--
-- ROTORSAK: tabellen (migration 20260720000000) har EN primärnyckel
-- (id), ETT unikt constraint (endpoint) och EN foreign key mot
-- auth.users(id) via user_id — men en foreign key-KOLUMN får INTE
-- automatiskt ett index av Postgres (bara den REFERERADE sidan, auth.
-- users.id, är indexerad via sin egen primärnyckel). `user_id` och
-- `revoked_at` har alltså ALDRIG haft något index sedan tabellen skapades.
-- Detta är precis den typ av "foreign key utan index"-situation Supabase
-- Performance Advisor rutinmässigt flaggar, och den matchar här verkligen
-- de faktiska frågemönstren ovan — inte bara en generisk varning.
--
-- VARFÖR EN PARTIELL INDEX, INTE EN VANLIG: samtliga fyra frågor ovan
-- filtrerar (direkt eller indirekt, eftersom alla rader som faktiskt
-- används av send-push/service-monitor måste ha revoked_at IS NULL för
-- att vara meningsfulla att skicka push till) på `revoked_at IS NULL`.
-- En PARTIELL index (WHERE revoked_at IS NULL) täcker alla fyra
-- frågemönstren (med ELLER utan user_id-filter — user_id som ledande
-- kolumn fungerar för frågor SOM har user_id-filtret, och hela det
-- partiella indexet fungerar som en redan kraftigt förminskad svepning
-- för frågor UTAN user_id-filter, eftersom återkallade prenumerationer
-- —som ackumuleras över tid utan att raderas, se EF-koden— aldrig ingår)
-- och blir dessutom MINDRE än ett fullständigt index eftersom återkallade
-- rader utesluts helt.
--
-- SÄKERT ATT KÖRA: CREATE INDEX IF NOT EXISTS, CONCURRENTLY (ingen
-- blockerande lock på tabellen under byggandet — rimligt även om
-- tabellen skulle vara liten idag, eftersom CONCURRENTLY aldrig är
-- skadligt, bara något långsammare att bygga). Lägger INTE till, tar INTE
-- bort och ändrar INTE någon RLS-policy eller behörighet. Ingen data
-- berörs eller flyttas.
--
-- VERIFIERA FÖRE/EFTER (kör i SQL Editor, läsande, ofarligt):
--   EXPLAIN (ANALYZE, BUFFERS)
--     SELECT id, user_id, endpoint, p256dh, auth_key
--       FROM push_subscriptions
--      WHERE revoked_at IS NULL;
--   → jämför "Seq Scan"/kostnad FÖRE denna migration mot "Index Scan"/
--     lägre kostnad EFTER.
--
-- ROLLBACK:
--   DROP INDEX CONCURRENTLY IF EXISTS push_subscriptions_user_id_active_idx;
-- ============================================================

-- OBS: CREATE INDEX CONCURRENTLY kan INTE köras inuti en explicit
-- transaktion (BEGIN/COMMIT) — måste köras som ett eget, enskilt
-- SQL-editor-anrop, inte via `supabase db push`s vanliga transaktions-
-- wrapper. Dokumenterat här, inte paketerat i en transaktionsblockerad
-- migrationskörning.

CREATE INDEX CONCURRENTLY IF NOT EXISTS push_subscriptions_user_id_active_idx
  ON public.push_subscriptions (user_id)
  WHERE revoked_at IS NULL;
